export const messages: Record<Language, Record<string, string>> = { zh, en };

export function translate(lang: Language, key: string, params?: I18nParams): string {
  const table = messages[lang] || messages.zh;
  let text = table[key];
  if (text === undefined) text = messages.zh[key];
  if (text === undefined) text = key;
  if (params) {
    for (const k of Object.keys(params)) {
      text = text.split('{' + k + '}').join(String(params[k]));
    }
  }
  return text;
}

